#!/usr/bin/env python3
"""Add the Automation settings row, panel and on-demand loader to the
dashboard sources (EN and zh-CN). Run after tools/add_body_comfort_dashboard.py.
The panel UI itself lives in dashboard_automation.js, served as /automation.js
(automation_ui_js.h, generated by tools/build_dashboard.py) so the embedded
dashboard stays inside its gzip budget.

Usage: python3 tools/add_automation_dashboard.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARKER = 'id="panelAutomation"'

TEXT = {
    "en": {
        "rowKey": "Automation", "rowDesc": "When / if / then rules for Body CAN signals.",
        "back": "Back", "settings": "Settings", "title": "Automation",
        "sub": "Rules run on the T2CAN while the car is awake. Mirror fold, rear fog on and frunk open never run in D.",
        "loading": "Loading…", "failed": "Could not load the automation panel", "on": "ON", "off": "OFF",
    },
    "zh-CN": {
        "rowKey": "自动化", "rowDesc": "基于车身 CAN 信号的 当 / 如果 / 则 规则。",
        "back": "返回", "settings": "设置", "title": "自动化",
        "sub": "车辆唤醒时规则在 T2CAN 上运行。折叠后视镜、开启后雾灯和打开前备箱在 D 挡不会执行。",
        "loading": "加载中…", "failed": "无法加载自动化面板", "on": "开", "off": "关",
    },
}

BACK_SVG = ('<svg aria-hidden="true" class="backIcon" viewBox="0 0 24 24"><path d="M15 18l-6-6 6-6" '
            'fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round" '
            'stroke-width="2"></path></svg>')


def settings_row(t):
    return ('<div class="listrow clickable" data-panel="panelAutomation" id="automationSettingsRow">'
            f'<div><div class="listkey">{t["rowKey"]}</div><div class="listdesc">{t["rowDesc"]}</div></div>'
            '<div class="rowRight"><span class="value" id="automationRowState">—</span><span class="chev">›</span></div></div>')


def panel(t):
    return (f'<section class="panel" id="panelAutomation"><div class="panelin"><div class="paneltop">'
            f'<button aria-label="{t["back"]}" class="backbtn">{BACK_SVG}</button><div class="paneltitle">{t["settings"]}</div></div>'
            f'<div class="panelHero">{t["title"]}</div><div class="panelSub">{t["sub"]}</div>'
            f'<div id="autoBody"><div class="softNote">{t["loading"]}</div></div></div></section>')


LOADER = r'''<script>(()=>{
window.AUTO_LANG=__LANG__;
const T=__TEXT__;
let loading=null,mounted=false;
function load(){if(window.AutoUi)return Promise.resolve();if(loading)return loading;
loading=new Promise((res,rej)=>{const s=document.createElement('script');s.src='/automation.js';s.onload=()=>res();s.onerror=()=>{loading=null;s.remove();rej(new Error('/automation.js'))};document.head.appendChild(s)});return loading}
window.autoRowUpdate=st=>{const v=document.getElementById('automationRowState');if(v&&st)v.textContent=(st.enabled?T.on:T.off)+' · '+((st.rules||[]).length)};
window.fetchAutomation=async()=>{const el=document.getElementById('autoBody');if(!el)return;
try{await load();if(!mounted){mounted=true;await window.AutoUi.mount(el)}else await window.AutoUi.refresh()}
catch(e){mounted=false;el.innerHTML='<div class="softNote">'+T.failed+' · '+String(e.message||e).replace(/[<>&]/g,'')+'</div>'}};
setTimeout(async()=>{try{const r=await fetch('/api/auto',{cache:'no-store'});if(r.ok)window.autoRowUpdate(await r.json())}catch(e){}},1800);
})();</script>'''


def patch(path: Path, lang: str) -> bool:
    t = TEXT[lang]
    src = path.read_text(encoding="utf-8")
    if MARKER in src:
        print(f"{path}: already patched")
        return False
    if 'id="panelBodyComfort"' not in src:
        sys.exit(f"{path}: run tools/add_body_comfort_dashboard.py first")
    lines = src.split("\n")

    def find(pred, what):
        hits = [i for i, l in enumerate(lines) if pred(l)]
        if len(hits) != 1:
            sys.exit(f"{path}: anchor {what!r} found {len(hits)} times")
        return hits[0]

    # 1) Settings row right after the Body Comfort row.
    i = find(lambda l: 'id="bodyComfortSettingsRow"' in l, "body comfort row")
    lines.insert(i + 1, settings_row(t))
    # 2) Panel before the settings detail panels marker.
    i = find(lambda l: l.strip() == "<!-- Settings detail panels -->", "panels marker")
    lines.insert(i, panel(t))
    # 3) Poll while the panel is open.
    i = find(lambda l: l.startswith("const pollLast={"), "pollLast")
    assert "body:0," in lines[i]
    lines[i] = lines[i].replace("body:0,", "body:0,auto:0,", 1)
    i = find(lambda l: "else if(p==='panelBodyComfort')pollDue('body'" in l, "body poll")
    lines.insert(i + 1, "    else if(p==='panelAutomation')pollDue('auto',1500,()=>window.fetchAutomation?.(),now,force);")
    # 4) Loader before the select-sheet enhancer script.
    i = find(lambda l: "sheet=q('selectSheet')" in l, "select sheet script")
    assert lines[i - 1] == "<script>(()=>{", lines[i - 1]
    loader = (LOADER.replace("__LANG__", json.dumps(lang))
              .replace("__TEXT__", json.dumps(t, ensure_ascii=False, separators=(",", ":"))))
    lines.insert(i - 1, loader)
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"{path}: patched")
    return True


if __name__ == "__main__":
    patch(ROOT / "dashboard_source.html", "en")
    patch(ROOT / "zh-CN" / "dashboard_source_zh-CN.html", "zh-CN")
